export const modules: Module[] = content.map((m) => ({
  ...m,
  steps: m.steps.map((s): Step => (HIGHLIGHTS[s.id] ? { ...s, highlight: HIGHLIGHTS[s.id] } : s)),
}));

export const allSteps: Step[] = modules.flatMap((m) => m.steps);

export function findStep(id: string): { module: Module; step: Step; index: number } | undefined {
  const index = allSteps.findIndex((s) => s.id === id);
  if (index === -1) return undefined;
  const step = allSteps[index];
  const module = modules.find((m) => m.steps.includes(step))!;
  return { module, step, index };
}
